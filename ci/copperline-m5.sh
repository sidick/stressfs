#!/usr/bin/env bash
# ci/copperline-m5.sh
#
# M5 (docs/implementation-plan.md section 3's M5 entry): "The verdict
# matrix: FFS V40, FFS V47, PFS3-AIO." Runs `stressfs conform` and
# `stressfs random` (a handful of fixed seeds) against each working
# handler tier under Copperline, headlessly and reproducibly -- the
# same established `--run`/`--exit-on-return` pattern as
# ci/copperline-m0.sh through -m4.sh, now factored through
# ci/m5/lib.sh so it isn't copy-pasted three times (see that file).
#
# Tiers:
#   ffs-v47  -- Kickstart 3.2.2 (V47.111), the HDF+ROM pair M0-M4
#               already used (~/kick32.a1200.rom + ~/os_drive.hdf),
#               [ide] master, A1200 profile.
#   ffs-v40  -- Kickstart 3.1 (40.68), A3000-profile ROM
#               (~/kicksmash32/amiga-os-310-a3000.rom). FastFileSystem
#               V40 is a ROM-resident module on this ROM (confirmed via
#               `romtool scan`), so the only thing that needs building
#               is a plain FFS partition -- see
#               ci/m5/build-ffs-v40-hdf.sh for why amibake can't supply
#               this (no AmigaOS 3.1 base) and why a full OS install
#               isn't needed either. IMPORTANT: this ROM's scsi.device
#               cannot drive Copperline's Gayle `[ide]` emulation (the
#               guest hangs retrying an "IDE: unimplemented command
#               0xFF"); [scsi] controller="a3000" (the A3000's native
#               SCSI, which is what this Kickstart's scsi.device
#               actually expects) works. This is itself an M5 finding,
#               documented in docs/verdict-matrix.md.
#   pfs3-aio -- NOT run. See ci/m5/pfs3-aio-status.md for the full
#               account of what was tried; the short version is that
#               PFS3's own disk-presence check refuses every HDF this
#               session built or reused, isolated to be PFS3-specific
#               (the identical HDF/unit formats normally as FFS).
#
# A fresh HDF is rebuilt before every `stressfs conform` pass (not just
# once): a second conform run against an already-exercised FFS V40
# volume was observed to hang the guest (ci/m5/build-ffs-v40-hdf.sh's
# header comment has the detail). `stressfs random` passes reuse one
# freshly-built volume across their SEED=1/2/3 sub-passes instead of
# reformatting between them -- M4 already established that `random`'s
# own fixture path is idempotent across repeated runs against the SAME
# handler (ci/copperline-m4.sh's determinism check runs it twice in a
# row), so this is the already-proven-safe pattern, not a new risk.
#
# "a handful of fixed seeds plus a nightly random one" (the plan's own
# wording): SEED=1,2,3 here are the fixed seeds; the nightly random one
# is NOT generated by this script (a fixed milestone run must stay
# deterministic) -- .github/workflows/ci.yml's nightly job derives one
# from the run date instead, see that file's comment.
#
# Needs real AmigaOS Kickstart ROMs (both tiers) and, for FFS V47, the
# M0-M4 HDF -- all licensed/personal assets this repo cannot ship, same
# caveat as every earlier milestone's scripts. FFS V40's HDF is built
# fresh by this script (amitools only, no personal asset needed beyond
# the ROM).
#
# Usage:
#   COPPERLINE_ROM_V47=/path/to/kick322.rom \
#   COPPERLINE_HDF_V47=/path/to/os_drive.hdf \
#   COPPERLINE_ROM_V40=/path/to/kick31.rom \
#     ci/copperline-m5.sh
set -eu

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=ci/m5/lib.sh
. "$ROOT/ci/m5/lib.sh"

ROM_V47="${COPPERLINE_ROM_V47:-$HOME/kick32.a1200.rom}"
HDF_V47="${COPPERLINE_HDF_V47:-$HOME/os_drive.hdf}"
VOLUME_V47="${COPPERLINE_VOLUME_V47:-Work:}"

ROM_V40="${COPPERLINE_ROM_V40:-$HOME/kicksmash32/amiga-os-310-a3000.rom}"
HDF_V40="$ROOT/build-m68k/m5-assets/ffs-v40.hdf"
VOLUME_V40="Work:"

SEEDS="${M5_SEEDS:-1 2 3}"
RANDOM_OPS="${M5_RANDOM_OPS:-2000}"
REPORTS="$ROOT/build-m68k/m5-assets/reports"

mkdir -p "$REPORTS/ffs-v40" "$REPORTS/ffs-v47"

# ---------------------------------------------------------------------
# FFS V47
# ---------------------------------------------------------------------
if [ -f "$ROM_V47" ] && [ -f "$HDF_V47" ]; then
  CONFIG_V47="$(mktemp -t copperline-m5-v47-XXXXXX.toml)"
  m5_write_config "$CONFIG_V47" "$ROM_V47" "
[machine]
profile = \"A1200\"

[ide]
master = \"$HDF_V47\"
"
  m5_run_once "$CONFIG_V47" conform "VOLUME $VOLUME_V47 TIER ffs-v47 CONFORM" \
    "$REPORTS/ffs-v47"
  for s in $SEEDS; do
    m5_run_once "$CONFIG_V47" "random-seed$s" \
      "VOLUME $VOLUME_V47 TIER ffs-v47 SEED $s RANDOM OPS $RANDOM_OPS" \
      "$REPORTS/ffs-v47"
  done
  rm -f "$CONFIG_V47"
else
  echo "== skipping ffs-v47: ROM ($ROM_V47) or HDF ($HDF_V47) not found ==" >&2
fi

# ---------------------------------------------------------------------
# FFS V40
# ---------------------------------------------------------------------
if [ -f "$ROM_V40" ]; then
  CONFIG_V40="$(mktemp -t copperline-m5-v40-XXXXXX.toml)"
  m5_write_config "$CONFIG_V40" "$ROM_V40" "
[machine]
profile = \"A3000\"

[scsi]
controller = \"a3000\"
unit0 = \"$HDF_V40\"
"
  "$ROOT/ci/m5/build-ffs-v40-hdf.sh" "$HDF_V40"
  m5_run_once "$CONFIG_V40" conform "VOLUME $VOLUME_V40 TIER ffs-v40 CONFORM" \
    "$REPORTS/ffs-v40"

  # A fresh volume before EVERY pass, not just once per tier: the
  # first M5 run of this script found that `stressfs random` against
  # an ALREADY-EXERCISED FFS V40 volume also hangs (SEED=2 and SEED=3,
  # run back-to-back against the same volume SEED=1 had just used,
  # both hit the outer timeout below with zero report produced) --
  # the same symptom `stressfs conform`'s own re-run hang has (see
  # ci/m5/build-ffs-v40-hdf.sh's header comment), now additionally
  # confirmed for `random`. docs/verdict-matrix.md's phase-1 gate
  # section records this as a real FFS V40 / this session's Copperline
  # SCSI environment finding, not a harness bug -- but AVOIDING it
  # operationally (by reformatting here) is what lets every fixed seed
  # actually get its own report instead of losing 2 of 3 to a hang
  # that produces no data at all.
  for s in $SEEDS; do
    "$ROOT/ci/m5/build-ffs-v40-hdf.sh" "$HDF_V40"
    m5_run_once "$CONFIG_V40" "random-seed$s" \
      "VOLUME $VOLUME_V40 TIER ffs-v40 SEED $s RANDOM OPS $RANDOM_OPS" \
      "$REPORTS/ffs-v40"
  done
  rm -f "$CONFIG_V40"
else
  echo "== skipping ffs-v40: ROM ($ROM_V40) not found ==" >&2
fi

echo ""
echo "== pfs3-aio: NOT run -- see ci/m5/pfs3-aio-status.md =="
echo ""
echo "== M5 Copperline runs complete. Reports under $REPORTS/. =="
echo "   Regenerate docs/verdict-matrix.md with:"
echo "     ci/m5/gen-matrix.sh $REPORTS --write"
echo "   or, to update the checked-in snapshot other tooling reads by default:"
echo "     rm -rf ci/m5/reports && cp -r $REPORTS ci/m5/reports && ci/m5/gen-matrix.sh --write"
